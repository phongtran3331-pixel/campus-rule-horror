let fail = 0;
for (const [scene, cfg] of Object.entries(MAP)) {
  const p = join(OUT, scene, "campus_text.json");
  if (!existsSync(p)) { console.error(`✗ 缺文件 ${p}`); fail++; continue; }
  const j = JSON.parse(readFileSync(p, "utf8"));
  if (cfg.intro) j.intro = cfg.intro;
  if (cfg.rooms) {
    j.rooms = cfg.rooms;
    const seen = new Map();
    const loose = new Set(cfg.loose ?? []);
    const mark = (id, where) => {
      if (!j.events[id]) { console.error(`✗ ${scene}: ${where} 引用不存在的事件 ${id}`); fail++; return; }
      if (seen.has(id)) { console.error(`✗ ${scene}: 事件 ${id} 重复出现（${seen.get(id)} / ${where}）`); fail++; return; }
      seen.set(id, where);
    };
    for (const id of loose) mark(id, "无房间平铺");
    for (const [room, ids] of Object.entries(cfg.assign)) {
      if (!cfg.rooms[room]) { console.error(`✗ ${scene}: assign 房间 ${room} 不在 rooms`); fail++; }
      for (const id of ids) { mark(id, `房间「${room}」`); j.events[id].room = room; }
    }
    for (const [pid, kids] of Object.entries(cfg.children ?? {})) {
      if (!j.events[pid]) { console.error(`✗ ${scene}: children 父事件 ${pid} 不存在`); fail++; continue; }
      for (const c of kids) { mark(c, `事件${pid}的子分支`); j.events[c].room = j.events[pid].room; }
      j.events[pid].children = kids;
    }
    for (const id of Object.keys(j.events)) {
      if (!seen.has(id)) { console.error(`✗ ${scene}: 事件 ${id}「${j.events[id].choice}」未被任何房间或子分支收录`); fail++; }
    }
  }
  writeFileSync(p, JSON.stringify(j, null, 1).replace(/\n /g, "\n ") + "\n");
  console.log(`✓ ${scene}${cfg.rooms ? `（${Object.keys(cfg.rooms).length} 房间）` : "（平铺）"}`);
}
process.exit(fail ? 1 : 0);
