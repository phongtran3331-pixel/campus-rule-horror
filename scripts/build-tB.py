wiki = json.load(open(os.path.join(ROOT, "client", "public", "wiki.json"), encoding="utf-8"))
errs = []
refcount = {}
for e in events.values():
    for c in (e.get("children") or []):
        if c not in events: errs.append(f"children 指向不存在的事件: {c}")
        refcount[c] = refcount.get(c, 0) + 1
dup = [k for k, v in refcount.items() if v > 1]
if dup: errs.append(f"事件被多个父级引用: {dup}")
for eid, e in events.items():
    r = e.get("room")
    if r and r not in ROOMS: errs.append(f"{eid} room 未定义: {r}")

GRANT_RE = re.compile(r"(?:获得物品?|\{获得):([^()（）]+)\((普|高|关|耗)#(\d+)\)\}?")
CONSUME_RE = re.compile(r"\{消耗:([^()（）]+)\((普|高|关|耗)#(\d+)\)\}")
def check_text(eid, text):
    for m in list(GRANT_RE.finditer(text)) + list(CONSUME_RE.finditer(text)):
        name, seg, num = m.group(1).strip(), m.group(2), int(m.group(3))
        w = wiki.get(name)
        if not w: errs.append(f"{eid}: Wiki 缺物品「{name}」"); continue
        if w.get("seg") != seg: errs.append(f"{eid}: 「{name}」段不符 标注{seg}#{num} wiki={w.get('seg')}")
        if "num" in w and w["num"] != num: errs.append(f"{eid}: 「{name}」号不符 标注{seg}#{num} wiki={w['seg']}#{w['num']}")
for eid, e in events.items():
    check_text(eid, e["result"])
    check_text(eid, e.get("result_taken", ""))

def ref_ok(ref):
    seg, num = ref.split("#")
    for name, w in wiki.items():
        if w.get("seg") != seg: continue
        if "num" not in w: return True
        if w["num"] == int(num): return True
    return False
for eid, e in events.items():
    for ref in (e.get("need") or []) + (e.get("needAny") or []) + (e.get("consume") or []):
        if not ref_ok(ref): errs.append(f"{eid}: 前置/消耗 ref 无对应物品: {ref}")

if errs:
    print("校验失败：")
    for x in errs: print(" -", x)
    sys.exit(1)

