/* 从文本库取探索文本：精确子房间 → 节点 → 通用兜底 */
export function exploreText(roomId: string | null, nodeId: string, san: number,
  rand: () => number = Math.random): string {
  const pool = (roomId && EXPLORE_TEXT[roomId]) || EXPLORE_TEXT[nodeId];
  const line = pool ? pick(pool, rand) : null;
  if (!line) return "你仔细翻找了这个角落。";
  if (san < 40 && line.sanLowText) return line.sanLowText;
  if (san < 40 && rand() < 0.35) return "你揉了揉眼睛——角落里似乎有什么东西动了一下。再看时，只有灰尘。";
  return line.text;
}
